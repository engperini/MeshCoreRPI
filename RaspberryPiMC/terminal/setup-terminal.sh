#!/usr/bin/env bash
# MeshCoreRPI message terminal: RemoteTerm (web UI for messages, channels and
# contacts) connected to the native companion, optionally opened full-screen
# on the Pi's own display at login (kiosk). No phone needed.
#
# Install the companion first (install.sh), then:
#   curl -fsSL https://raw.githubusercontent.com/engperini/MeshCoreRPI/main/RaspberryPiMC/terminal/setup-terminal.sh | sudo bash
#   ... | sudo bash -s -- --kiosk      # also open it full-screen at desktop login
#   ... | sudo bash -s -- --no-kiosk   # remove the kiosk autostart again
#
# RemoteTerm: https://github.com/jkingsman/Remote-Terminal-for-MeshCore
set -euo pipefail

KIOSK=keep
for arg in "$@"; do
  case "$arg" in
    --kiosk) KIOSK=on ;;
    --no-kiosk) KIOSK=off ;;
    -h|--help) sed -n '2,12p' "$0" 2>/dev/null || true; exit 0 ;;
    *) echo "Unknown option: $arg (use --kiosk or --no-kiosk)" >&2; exit 2 ;;
  esac
done
if [[ $EUID -ne 0 ]]; then
  echo "Please run as root (pipe into: sudo bash)" >&2
  exit 1
fi

DIR=/opt/meshcorerpi-terminal
PORT="${RPI_TERMINAL_PORT:-8080}"
ENV_FILE=/etc/raspberrypimc/companion.env
COMPANION_PORT=5000
if [[ -f "$ENV_FILE" ]]; then
  p="$(grep -E '^RPI_COMPANION_TCP_PORT=' "$ENV_FILE" | tail -n1 | cut -d= -f2 || true)"
  [[ -n "$p" ]] && COMPANION_PORT="$p"
fi
DESKTOP_USER="${SUDO_USER:-$(logname 2>/dev/null || echo pi)}"
DESKTOP_HOME="$(getent passwd "$DESKTOP_USER" | cut -d: -f6)"

if ! systemctl is-enabled raspberrypimc-companion.service >/dev/null 2>&1; then
  echo "warning: raspberrypimc-companion is not installed/enabled; install it first:" >&2
  echo "  curl -fsSL https://raw.githubusercontent.com/engperini/MeshCoreRPI/main/install.sh | sudo bash" >&2
fi

# The companion package ships its own small dashboard on 8080; RemoteTerm replaces it.
if [[ -f "$ENV_FILE" && "$PORT" == "8080" ]] && ! grep -q '^RPI_COMPANION_WEB_ENABLE=0' "$ENV_FILE"; then
  echo "==> Disabling the companion's built-in dashboard (frees port 8080 for RemoteTerm)"
  if grep -q '^RPI_COMPANION_WEB_ENABLE=' "$ENV_FILE"; then
    sed -i 's/^RPI_COMPANION_WEB_ENABLE=.*/RPI_COMPANION_WEB_ENABLE=0/' "$ENV_FILE"
  else
    echo 'RPI_COMPANION_WEB_ENABLE=0' >> "$ENV_FILE"
  fi
  systemctl restart raspberrypimc-companion.service || true
  sleep 2
fi

if ! docker compose version >/dev/null 2>&1; then
  echo "==> Installing Docker"
  curl -fsSL https://get.docker.com | sh
fi

if ss -ltn "sport = :$PORT" | grep -q LISTEN && ! docker ps --format '{{.Names}}' | grep -q '^meshcorerpi-terminal-'; then
  echo "Port $PORT is already in use:" >&2
  ss -ltnp "sport = :$PORT" >&2 || true
  docker ps --format '  container: {{.Names}} ({{.Ports}})' | grep ":$PORT->" >&2 || true
  echo "Stop that service/container first (or set RPI_TERMINAL_PORT), then run this again." >&2
  exit 1
fi

echo "==> Setting up RemoteTerm in $DIR"
mkdir -p "$DIR/data"
cat > "$DIR/compose.yaml" <<EOF
# Generated by MeshCoreRPI setup-terminal.sh
services:
  remoteterm:
    image: docker.io/jkingsman/remoteterm-meshcore:latest
    restart: unless-stopped
    ports:
      - "0.0.0.0:${PORT}:8000"
    environment:
      MESHCORE_TCP_HOST: host.docker.internal
      MESHCORE_TCP_PORT: "${COMPANION_PORT}"
      MESHCORE_DATABASE_PATH: /app/data/meshcore.db
      # RemoteTerm bots run arbitrary Python: keep them off until the UI is protected.
      MESHCORE_DISABLE_BOTS: "true"
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ./data:/app/data
EOF
docker compose -p meshcorerpi-terminal -f "$DIR/compose.yaml" pull
docker compose -p meshcorerpi-terminal -f "$DIR/compose.yaml" up -d

echo -n "==> Waiting for RemoteTerm on port $PORT"
for _ in $(seq 1 60); do
  if curl -fs "http://127.0.0.1:${PORT}/" >/dev/null 2>&1; then echo " ok"; break; fi
  echo -n "."; sleep 2
done
echo

AUTOSTART="$DESKTOP_HOME/.config/autostart/meshcorerpi-kiosk.desktop"
if [[ "$KIOSK" == "on" ]]; then
  echo "==> Enabling kiosk for desktop user '$DESKTOP_USER'"
  if ! command -v chromium >/dev/null 2>&1 && ! command -v chromium-browser >/dev/null 2>&1; then
    apt-get update -qq && apt-get install -y chromium
  fi
  cat > /usr/local/bin/meshcorerpi-kiosk <<EOF
#!/usr/bin/env bash
# Opens the MeshCoreRPI message terminal full-screen once RemoteTerm answers.
URL="http://localhost:${PORT}/"
for _ in \$(seq 1 120); do curl -fs "\$URL" >/dev/null 2>&1 && break; sleep 1; done
BROWSER="\$(command -v chromium || command -v chromium-browser)"
exec "\$BROWSER" --kiosk --noerrdialogs --disable-infobars --no-first-run \\
  --password-store=basic --check-for-update-interval=31536000 \\
  --user-data-dir="\$HOME/.config/meshcorerpi-kiosk" "\$URL"
EOF
  chmod 0755 /usr/local/bin/meshcorerpi-kiosk
  mkdir -p "$(dirname "$AUTOSTART")"
  cat > "$AUTOSTART" <<'EOF'
[Desktop Entry]
Type=Application
Name=MeshCoreRPI terminal
Comment=Open the MeshCore message terminal full-screen
Exec=/usr/local/bin/meshcorerpi-kiosk
X-GNOME-Autostart-enabled=true
EOF
  chown -R "$DESKTOP_USER:" "$DESKTOP_HOME/.config/autostart"
  echo "    Kiosk opens at the next desktop login (needs Raspberry Pi OS with Desktop and auto-login)."
  echo "    Leave it with Alt+F4; disable with: ... | sudo bash -s -- --no-kiosk"
elif [[ "$KIOSK" == "off" ]]; then
  rm -f "$AUTOSTART"
  echo "==> Kiosk autostart removed"
fi

ip="$(hostname -I 2>/dev/null | awk '{print $1}')"
echo
echo "Message terminal ready: http://${ip:-<pi-ip>}:${PORT}  (on the Pi itself: http://localhost:${PORT})"
echo "RemoteTerm data: $DIR/data   Update: docker compose -p meshcorerpi-terminal -f $DIR/compose.yaml pull && ... up -d"
echo "Keep it on your LAN: RemoteTerm has no login."
